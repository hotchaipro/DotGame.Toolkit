namespace DotGame.Toolkit.Fonts;

/// <summary>
/// How lines sit in a <see cref="TextLayout"/>'s width.
/// </summary>
public enum TextAlignment
{
    /// <summary>Lines start at the left of the width.</summary>
    Left,
    /// <summary>Lines are centered in the width.</summary>
    Center,
    /// <summary>Lines end at the right of the width.</summary>
    Right,
}
